def get_locale(lang_code: str) -> Dict[str, Any]:
    """Retrieve locale dictionary, with automatic fallback to en-IN."""
    code = (lang_code or "en-IN").strip()
    return LOCALES.get(code) or LOCALES.get(code.split("-")[0] + "-IN") or LOCALES["en-IN"]

def format_msg(lang_code: str, key: str, **kwargs) -> str:
    """Format localized message string with safe fallback."""
    locale = get_locale(lang_code)
    template = locale.get(key) or LOCALES["en-IN"].get(key, "")
    try:
        return template.format(**kwargs)
    except Exception:
        return template
